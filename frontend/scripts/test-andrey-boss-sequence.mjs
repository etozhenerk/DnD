import assert from 'node:assert/strict';
import {readFile, access} from 'node:fs/promises';
import {createServer} from 'vite';
const server = await createServer({appType:'custom', logLevel:'silent', server:{middlewareMode:true}});
try {
  const {penisuelaGalleryGameplay: runtimeDefinition, penisuelaGalleryHeroes: heroes, penisuelaSessionPreview: preview} = await server.ssrLoadModule('/src/entities/campaign-session/model/data.ts');
  await access(runtimeDefinition.bossSequence.transformationVideo.source);
  await access(runtimeDefinition.bossSequence.aftermath.deathVideo.source);
  const definition = structuredClone(runtimeDefinition);
  delete definition.bossSequence.transformationVideo.source;
  delete definition.bossSequence.aftermath.deathVideo.source;
  const {createBossSequenceEvents: create} = await server.ssrLoadModule('/src/features/navigate-campaign-scene/model/bossSequenceCommands.ts');
  const {replayGalleryEvents: replay} = await server.ssrLoadModule('/src/entities/campaign-session/model/gallerySession.ts');
  const journal = await server.ssrLoadModule('/src/entities/campaign-session/model/gallerySessionJournal.ts');
  const {getStoryActionAvailability: available} = await server.ssrLoadModule('/src/features/navigate-campaign-scene/model/storyActionRules.ts');
  const seq=definition.bossSequence, scene=preview.scenes.find(x=>x.id===seq.sceneId);
  let serial=0;
  const wrap=(events, commandId)=>events.map(e=>({...e,id:`event-${++serial}`,commandId,sceneScopeId:seq.sceneId}));
  const seed=journal.createGallerySessionStartedEvent({definition,heroes,existingInventory:[],eventId:'seed',commandId:'seed'});
  let events=[seed];
  const run=(cmd,log=events,def=definition)=>create(def,replay(log,def),heroes,cmd,()=>10);
  assert.deepEqual(run('video-ended'),[]);
  assert.deepEqual(run('start-transformation'),[]);
  assert.deepEqual(run('first-victory'),[]);
  events.push(...wrap(run('start'),'start'));
  assert.equal(replay(events,definition).combat.encounterId,seq.firstEncounterId);
  assert.deepEqual(run('start'),[], 'do not restart live fight');
  assert.deepEqual(run('first-victory'),[], 'cannot bypass surviving boss');
  events.push(...wrap([{type:'combat-damage-resolved',targetId:heroes[0].id,amount:5,text:'Ранение героя.'}],'hero-damage'));
  events.push(...wrap(['battle','location','campaign'].map(scope=>({type:'combat-action-used',actionId:'fixture-action',sourceId:'fixture-source',resourceKey:`fixture-${scope}`,scope,max:1})),'resource-use'));
  const beforeKill=replay(events,definition);
  const oldHp=beforeKill.combat.enemies[seq.firstEncounterId].hp;
  events.push(...wrap([{type:'combat-damage-resolved',targetId:seq.firstEncounterId,amount:oldHp,text:'Добивающий удар.'}],'kill'));
  const defeated=replay(events,definition);
  assert.deepEqual(create(definition,{...defeated,heroHp:Object.fromEntries(heroes.map(h=>[h.id,0]))},heroes,'first-victory'),[]);
  assert.deepEqual(create(definition,{...defeated,flags:{...defeated.flags,'andrey-defeat-fallback':true}},heroes,'first-victory'),[]);
  const withVideo=structuredClone(runtimeDefinition);
  const intermissionEvents=[...events,...wrap(run('first-victory',events,withVideo),'confirm-first')];
  assert.equal(replay(intermissionEvents,withVideo).combat,null);
  assert.equal(replay(intermissionEvents,withVideo).resourceUses['fixture-battle'],1,'Closing victory does not yet reset battle resources');
  assert.deepEqual(run('video-ended',intermissionEvents,withVideo),[],'Video cannot complete before the explicit button');
  const videoEvents=[...intermissionEvents,...wrap(run('start-transformation',intermissionEvents,withVideo),'transform')];
  assert.equal(replay(videoEvents,withVideo).combat,null,'hold next fight during movie');
  assert.equal(replay(videoEvents,withVideo).flags['andrey-transformation-started'],true);
  assert.deepEqual(run('start-transformation',videoEvents,withVideo),[],'Button cannot run twice');
  assert.equal(replay(videoEvents,withVideo).flags['andrey-transformation-finished'],undefined);
  const afterVideo=[...videoEvents,...wrap(run('video-ended',videoEvents,withVideo),'transform')];
  assert.equal(replay(afterVideo,withVideo).combat.encounterId,seq.secondEncounterId);
  assert.deepEqual(run('video-ended',afterVideo,withVideo),[], 'ended/skip must be idempotent');
  const undoVideo=replay([...afterVideo,...wrap([{type:'action-corrected',correctedCommandId:'transform'}],'undo-video')],withVideo);
  assert.equal(undoVideo.combat,null,'Undo the explicit transition returns the kneeling scene');
  assert.equal(undoVideo.flags['andrey-phase-one-defeated'],true);
  assert.equal(undoVideo.flags['andrey-transformation-started'],undefined);
  assert.equal(undoVideo.flags['andrey-transformation-finished'],undefined);
  events.push(...wrap(run('first-victory'),'confirm-no-video'));
  assert.equal(replay(events,definition).combat,null,'Without a movie the intermission still waits for the button');
  events.push(...wrap(run('start-transformation'),'transform-no-video'));
  let state=replay(events,definition);
  assert.equal(state.combat.encounterId,seq.secondEncounterId);
  assert.equal(state.combat.enemies[seq.secondEncounterId].hp,definition.encounters.find(e=>e.id===seq.secondEncounterId).hp);
  assert.equal(state.combat.round,1);
  assert.equal(state.combat.pendingAttack,null);
  assert.deepEqual(state.heroHp,beforeKill.heroHp);
  assert.equal(state.resourceUses['fixture-battle'],undefined);
  assert.equal(state.resourceUses['fixture-location'],1);
  assert.equal(state.resourceUses['fixture-campaign'],1);
  assert.deepEqual(state.inventoryState,beforeKill.inventoryState);
  assert.deepEqual(state.counters,beforeKill.counters,'final fights do not increment preFinalCombats');
  assert.deepEqual(run('first-victory'),[]);
  assert.deepEqual(run('finish'),[],'second boss must also be defeated');
  const expectation={campaignId:definition.campaignId,definitionId:definition.id,definitionVersion:definition.version};
  const loaded=journal.parseStoredGallerySessionEnvelope(JSON.parse(JSON.stringify(journal.createStoredGallerySessionEnvelope(events,expectation))),expectation);
  assert.ok(loaded.ok);assert.deepEqual(replay(loaded.events,definition).combat,state.combat);
  const undone=replay([...events,...wrap(['transform-no-video','confirm-no-video','kill'].map(correctedCommandId=>({type:'action-corrected',correctedCommandId})),'undo')],definition);
  assert.equal(undone.combat.encounterId,seq.firstEncounterId);assert.equal(undone.combat.enemies[seq.firstEncounterId].hp,oldHp);
  assert.equal(undone.flags['andrey-phase-one-defeated'],undefined);
  events.push(...wrap([{type:'combat-damage-resolved',targetId:seq.secondEncounterId,amount:definition.encounters.find(e=>e.id===seq.secondEncounterId).hp,text:'Дракон побеждён.'}],'kill-dragon'));
  events.push(...wrap(run('finish'),'finish'));
  state=replay(events,definition);assert.equal(state.combat,null);assert.equal(state.flags['andrey-boss-defeated'],true);
  assert.deepEqual(run('finish'),[]);assert.deepEqual(run('start'),[]);
  const finalStory=definition.storyScenes.find(x=>x.id===seq.sceneId);
  assert.ok(!finalStory.actions.some(x=>x.id.startsWith('show-andrey-')));
  const exit=finalStory.actions.find(x=>x.id==='continue-3-post-crisis-orientation-shutdown');
  assert.equal(available(exit,{...beforeKill,flags:{'final-primary-physical':true}},definition),false);
  assert.equal(available(exit,{...state,flags:{...state.flags,'final-primary-physical':true}},definition),false, 'new happy ending replaces legacy exit');
  assert.equal(available(exit,{...state,flags:{...state.flags,'andrey-death-video-finished':false,'final-primary-physical':true}},definition),true, 'legacy URL remains compatible');

  assert.equal(state.flags['andrey-death-video-finished'],true,'no video file: return immediately');
  assert.equal(state.flags['andrey-hostages-captured'],false,'boss death frees remaining hostages');
  assert.deepEqual(run('death-video-ended'),[],'skip cannot run twice');
  const deathDef=structuredClone(definition); deathDef.bossSequence.aftermath.deathVideo.source=runtimeDefinition.bossSequence.aftermath.deathVideo.source;
  const beforeFinish=events.filter(e=>e.commandId!=='finish');
  let deathLog=[...beforeFinish,...wrap(create(deathDef,replay(beforeFinish,deathDef),heroes,'finish'),'kill-dragon')];
  let deathState=replay(deathLog,deathDef);
  assert.equal(deathState.combat,null);assert.equal(deathState.flags['andrey-boss-defeated'],true);
  assert.ok(!deathState.flags['andrey-death-video-finished'],'wait for real video when configured');
  const storedDeath=journal.parseStoredGallerySessionEnvelope(JSON.parse(JSON.stringify(journal.createStoredGallerySessionEnvelope(deathLog,expectation))),expectation);
  assert.ok(storedDeath.ok);assert.deepEqual(replay(storedDeath.events,deathDef).flags,deathState.flags,'reload preserves pending movie');
  const finishDeath=create(deathDef,deathState,heroes,'death-video-ended');
  deathLog.push(...wrap(finishDeath,'kill-dragon'));deathState=replay(deathLog,deathDef);
  assert.equal(deathState.flags['andrey-death-video-finished'],true);
  assert.deepEqual(create(deathDef,deathState,heroes,'death-video-ended'),[]);
  assert.deepEqual(create(deathDef,beforeKill,heroes,'death-video-ended'),[],'cannot skip death before victory');
  assert.deepEqual(create(deathDef,{...deathState,flags:{...deathState.flags,'andrey-defeat-fallback':true}},heroes,'death-video-ended'),[]);
  const undoDeath=replay([...deathLog,...wrap([{type:'action-corrected',correctedCommandId:'kill-dragon'}],'undo-death')],deathDef);
  assert.equal(undoDeath.combat.enemies[seq.secondEncounterId].hp,definition.encounters.find(e=>e.id===seq.secondEncounterId).hp,'undo restores dragon, not just video');
  assert.ok(!undoDeath.flags['andrey-boss-defeated']);assert.ok(!undoDeath.flags['andrey-death-video-finished']);
  assert.deepEqual(deathState.heroHp,state.heroHp);assert.deepEqual(deathState.inventoryState,state.inventoryState);
  const aftermathExit=finalStory.actions.find(a=>a.id==='continue-after-andrey-victory');
  assert.equal(aftermathExit.nextSceneId,'villa-after-andrey');assert.equal(available(aftermathExit,state,definition),true);
  const story=(id)=>definition.storyScenes.find(s=>s.id===id);
  const approach=story('villa-after-andrey').actions[0], reset=story('couple-voice-reset').actions[0], wedding=story('couple-voice-reset').actions[1];
  assert.equal(available(approach,beforeKill,definition),false);assert.equal(available(approach,state,definition),true);
  assert.equal(available(reset,state,definition),false);assert.equal(available(wedding,state,definition),false);
  let finalState={...state,flags:{...state.flags,...approach.outcome.flags}};
  assert.equal(available(reset,finalState,definition),true);
  finalState={...finalState,flags:{...finalState.flags,...reset.outcome.flags}};
  assert.equal(available(reset,finalState,definition),false);assert.equal(available(wedding,finalState,definition),true);
  assert.equal(wedding.nextSceneId,'wedding-epilogue');assert.equal(wedding.outcome.selectedEnding,'wedding');
  assert.ok(!Object.keys(wedding.outcome.flags).some(f=>f.includes('publication')),'wedding does not imply publishing consent');
  const guide=await readFile('content/campaigns/penisuela-session-preview-guide.md','utf8');
  for (const id of ['villa-after-andrey','couple-voice-reset','wedding-epilogue']) {
    const s=preview.scenes.find(s=>s.id===id);await access(s.background);assert.ok(guide.includes(s.readAloud));
  }

  for (const view of [scene,...scene.interactionViews]) await access(view.background);
  for (const eid of [seq.firstEncounterId,seq.secondEncounterId]) {
    const enc=definition.encounters.find(x=>x.id===eid), npc=definition.npcBehaviors.find(x=>x.encounterId===eid);
    assert.ok(npc.actions.some(action=>action.id===enc.attack.id&&action.target==='one-opponent'));
    assert.ok(npc.actions.some(action=>definition.combatActions.some(skill=>skill.id===action.id&&skill.characterId===eid)));
    for (const action of definition.combatActions.filter(x=>heroes.some(hero=>hero.id===x.characterId)&&x.encounterIds.includes('egorik-bungalow-guards'))) assert.ok(action.encounterIds.includes(eid));
  }
  console.log('Andrey PASS: victory confirmation, explicit intermission/video button, fresh dragon, preserved heroes/resources, reload, staged undo, defeat guards, endings and assets.');
} finally {await server.close();}
